"""Regenerates docs/TEST_REPORT.md from real runs (nothing in the report is typed by hand).

    python scripts/make_test_report.py

Runs: ruff, the full pytest suite (JUnit XML), check_keys.py --fake, and smoke_e2e.py against a
temporary demo-mode server. Exit code 0 only if everything passed.
"""
from __future__ import annotations

import datetime as dt
import os
import platform
import socket
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "TEST_REPORT.md"
ENV = os.environ | {"NO_PROXY": "127.0.0.1,localhost", "no_proxy": "127.0.0.1,localhost", "PYTHONIOENCODING": "utf-8"}


def run(cmd: list[str], env: dict[str, str] | None = None, timeout: int = 1800) -> tuple[int, str, float]:
    t0 = time.time()
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env=env or ENV, timeout=timeout)
    return p.returncode, (p.stdout + p.stderr), time.time() - t0


def strip_ansi(s: str) -> str:
    import re

    return re.sub(r"\x1b\[[0-9;]*m", "", s)


def main() -> int:
    ok = True
    lines: list[str] = []
    now = dt.datetime.now(dt.timezone(dt.timedelta(hours=7)))
    git = run(["git", "rev-parse", "--short", "HEAD"])[1].strip() if (ROOT / ".git").exists() else "not a git checkout"

    # 1. lint
    rc_l, out_l, t_l = run([sys.executable, "-m", "ruff", "check", "api", "scripts", "app.py"])
    ok &= rc_l == 0

    # 2. tests
    xml = Path(tempfile.mkdtemp()) / "junit.xml"
    rc_t, out_t, t_t = run([sys.executable, "-m", "pytest", "api/tests", "-q", "-p", "no:warnings", f"--junitxml={xml}"],
                           env=ENV | {"OFFLINE": "1", "NARRATION_VOICE": "0"})
    ok &= rc_t == 0
    suites: dict[str, list[tuple[str, str, float]]] = {}
    if xml.exists():
        for tc in ET.parse(xml).getroot().iter("testcase"):
            status = "FAIL" if tc.find("failure") is not None or tc.find("error") is not None else ("SKIP" if tc.find("skipped") is not None else "PASS")
            suites.setdefault(tc.get("classname", "").split(".")[-1], []).append((tc.get("name", ""), status, float(tc.get("time", 0))))
    total = sum(len(v) for v in suites.values())
    passed = sum(1 for v in suites.values() for _, s, _ in v if s == "PASS")
    failed = sum(1 for v in suites.values() for _, s, _ in v if s == "FAIL")
    skipped = total - passed - failed

    # 3. key check dry run
    rc_k, out_k, _ = run([sys.executable, "scripts/check_keys.py", "--fake"], timeout=120)
    ok &= rc_k == 0

    # 4. smoke test against a temporary demo server
    s = socket.socket(); s.bind(("127.0.0.1", 0)); port = s.getsockname()[1]; s.close()
    data = tempfile.mkdtemp()
    srv = subprocess.Popen([sys.executable, "-m", "uvicorn", "api.main:app", "--port", str(port)], cwd=ROOT,
                           env=ENV | {"OFFLINE": "1", "NARRATION_VOICE": "0", "DATA_DIR": data}, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        time.sleep(4)
        rc_s, out_s, t_s = run([sys.executable, "scripts/smoke_e2e.py", f"http://127.0.0.1:{port}"], timeout=180)
    finally:
        srv.terminate()
    ok &= rc_s == 0

    lines += [
        "# Test report", "",
        f"Generated by `scripts/make_test_report.py` on **{now:%Y-%m-%d %H:%M} WIB** · commit `{git}` · Python {platform.python_version()} · {platform.system()}.",
        "Every number below comes from an actual run. This run does **not** call the live Meta models (offline answers and an HTTP test double); the live runs are in LIVE_RUN.md and EVAL.md, the full status in VERIFICATION_REPORT.md.", "",
        "## Summary", "",
        "| Check | Result |", "|---|---|",
        f"| Lint (ruff) | {'✅ pass' if rc_l == 0 else '❌ fail'} ({t_l:.1f}s) |",
        f"| Automated tests (pytest) | {'✅' if rc_t == 0 else '❌'} {passed} passed, {failed} failed, {skipped} skipped of {total} ({t_t:.1f}s) |",
        f"| Key check dry run (`check_keys.py --fake`) | {'✅ pass' if rc_k == 0 else '❌ fail'} |",
        f"| End-to-end HTTP smoke (`smoke_e2e.py`, demo server) | {'✅ pass' if rc_s == 0 else '❌ fail'} ({t_s:.1f}s) |",
        f"| **Overall** | **{'✅ ALL PASSED' if ok else '❌ FAILURES'}** |", "",
        "## Tests by file", "",
    ]
    for suite, cases in sorted(suites.items()):
        sp = sum(1 for _, s_, _ in cases if s_ == "PASS")
        lines += [f"### {suite} ({sp}/{len(cases)})", "", "| Test | Result | Time |", "|---|---|---|"]
        lines += [f"| `{n}` | {'✅' if s_ == 'PASS' else ('⏭️' if s_ == 'SKIP' else '❌')} | {t:.2f}s |" for n, s_, t in cases]
        lines.append("")
    lines += ["## Key check dry run output", "", "```", strip_ansi(out_k).strip(), "```", "",
              "## End-to-end smoke output", "", "```", strip_ansi(out_s).strip(), "```", ""]
    if rc_l != 0:
        lines += ["## Lint output", "", "```", out_l.strip()[-3000:], "```", ""]
    if rc_t != 0:
        lines += ["## Test failures", "", "```", out_t.strip()[-6000:], "```", ""]
    lines += ["## Manual phone QA (fill in after testing with real photos)", "",
              "| # | Scenario | Date | Result | Diagnosis time | Notes |", "|---|---|---|---|---|---|"]
    lines += [f"| {i} | {n} | | | | |" for i, n in enumerate(
        ["Motorbike won't start", "Check a step (dark → good photo)", "Still broken → re-plan", "Water pump no water",
         "Leaking tap/hose", "Rice cooker → red stop", "Gas → gate stop", "Javanese voice", "English UI", "Hands-free voice",
         "Share link on 2nd phone", "4G speed"], 1)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {'ALL PASSED' if ok else 'FAILURES'} ({passed}/{total} tests)")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
